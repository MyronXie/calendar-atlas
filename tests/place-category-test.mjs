import assert from 'node:assert/strict';
import fs from 'node:fs/promises';import os from 'node:os';import path from 'node:path';
import {placeTypes,placeIndex} from '../lib/place-categories.js';
import {normalizePlace} from '../lib/organize.js';
import {readPlaces,updatePlaces} from '../server/csv-store.mjs';
const EXPECTED_TYPES=['food','fun','art','shop','out','sport','trans','stay','edu','home','other'];
assert.deepEqual(Object.keys(placeTypes).sort(),[...EXPECTED_TYPES].sort(),'placeTypes 应包含全部类型短码');
for(const k of EXPECTED_TYPES)assert.equal(typeof placeTypes[k],'string');
const a={location:'标准店名(分店)',aliases:'旧店名；共同简称',labels:'桌游',type:'entertainment'};
const b={location:'另一家店',aliases:'共同简称'};
const lookup=placeIndex([a,b],normalizePlace);assert.equal(lookup.get(normalizePlace('旧店名')),a);assert(!lookup.has(normalizePlace('共同简称')));
const dir=await fs.mkdtemp(path.join(os.tmpdir(),'atlas-labels-')),file=path.join(dir,'place.csv');
await fs.writeFile(file,'location,address,lat,lon,valid,type\r\nTest,,31,121,,other\r\n');
const before=await readPlaces(file);await updatePlaces(file,before.version,[{location:'Test',type:'entertainment',labels:'桌游；棋牌',aliases:'旧名称'}]);
const after=await readPlaces(file);assert.equal(after.places[0].labels,'桌游；棋牌');assert.equal(after.places[0].aliases,'旧名称');assert.equal(after.places[0].lat,'31');
console.log('Place classification, safe aliases and CSV persistence: passed');
